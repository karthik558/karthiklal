import { expect, test } from "@playwright/test"

test("portfolio rail supports chapters, keyboard and dragging", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("/")
  await expect(page.getByRole("status", { name: "Loading website" })).toBeHidden()
  const slider = page.getByRole("slider", { name: "Scroll through portfolio" })
  await expect(slider).toBeVisible()
  await page.getByRole("navigation", { name: "Portfolio chapters" }).getByRole("link", { name: "Selected work" }).click()
  await expect(page.locator("#portfolio")).toBeInViewport()
  await slider.focus()
  await slider.press("End")
  await expect(slider).toHaveAttribute("aria-valuenow", "100")
  await slider.press("Home")
  await expect(slider).toHaveAttribute("aria-valuenow", "0")
  const box = (await slider.boundingBox())!
  await page.mouse.move(box.x + 4, box.y + 20)
  await page.mouse.down()
  await page.mouse.move(box.x + 4, box.y + box.height * .5, { steps: 10 })
  await page.mouse.up()
  await expect.poll(async () => Number(await slider.getAttribute("aria-valuenow"))).toBeGreaterThan(10)
  await page.screenshot({ path: "/tmp/portfolio-scrollbar-desktop.png" })
})

