import { expect, test } from '@playwright/test'

test('story discovery opens a reader that follows the site theme and retains reading controls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/stories')
  await expect(page.getByRole('status', { name: 'Loading website' })).toBeHidden()
  const search = page.getByRole('textbox', { name: 'Search stories or tags' })
  await search.fill('no-story-matches-this-query')
  await expect(page.getByRole('heading', { name: 'No stories found.' })).toBeVisible()
  await page.getByRole('button', { name: 'RESET FILTERS' }).click()
  await page.getByRole('link', { name: 'READ STORY', exact: true }).first().click()
  const reader = page.locator('.story-reader')
  await expect(reader).toBeVisible()
  const background = await page.locator('body').evaluate(element => getComputedStyle(element).backgroundColor)
  await expect(reader).toHaveCSS('background-color', background)
  await page.getByTitle('Reader Settings (Themes, Font size, Font style)', { exact: true }).click()
  await page.getByRole('button', { name: 'Midnight', exact: true }).click()
  await expect(reader).not.toHaveCSS('background-color', background)
  await page.getByRole('button', { name: 'Site theme', exact: true }).click()
  await expect(reader).toHaveCSS('background-color', background)
  await page.getByRole('button', { name: 'Close reader settings', exact: true }).click()
  await page.getByTitle('Switch to Book Mode', { exact: true }).click()
  await expect(page.getByTitle('Switch to Scroll Mode', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close reader' }).click()
  await expect(page).toHaveURL(/\/stories$/)
})

test('contact form retains custom subjects, validation, and submission feedback with a mocked delivery', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  let submitted: Record<string, string> | undefined
  await page.route('**/api/contact', async route => {
    submitted = route.request().postDataJSON()
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true }) })
  })
  await page.goto('/contact')
  await expect(page.getByRole('status', { name: 'Loading website' })).toBeHidden()
  await page.getByLabel('YOUR NAME *', { exact: true }).fill('Preview User')
  await page.getByLabel('YOUR EMAIL *', { exact: true }).fill('preview@example.com')
  await page.getByLabel('YOUR MESSAGE *', { exact: true }).fill('Testing the revised contact form layout.')
  await page.getByRole('button', { name: 'SEND MESSAGE', exact: true }).click()
  await expect(page.getByRole('combobox')).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('combobox').click()
  await page.getByRole('option', { name: 'Other / Custom subject', exact: true }).click()
  await page.locator('input[name=custom_subject]').fill('Portfolio design review')
  await page.getByRole('button', { name: 'SEND MESSAGE', exact: true }).click()
  await expect(page.getByText(/Thank you for reaching out, Preview User!/)).toBeVisible()
  expect(submitted?.subject).toBe('Portfolio design review')
  await expect(page.getByLabel('YOUR NAME *', { exact: true })).toHaveValue('')
})
